def render(source: str) -> str:
    lines = [HEADER.format(**SECTIONS)]
    groups = _groups(source)
    notes = _literal_dict(source, "NOTES")
    group_docs = _literal_dict(source, "GROUPS")
    lines.append("\n\n" + banner("eng groups: one class per group of calls (eng.clip, eng.model, eng.vae...)"))
    for group, methods in groups.items():
        lines.append("\n\n" + banner(f"eng.{group}: {group_docs.get(group, '')}", "-"))
        lines.append(f"\nclass _{group.capitalize()}:\n")
        lines.append(_docstring(f"``eng.{group}``: {group_docs.get(group, '')}", "    "))
        for method, row in methods:
            name = f"{group}.{method}"
            params = ", ".join(a for a in ("self", _params(row)) if a)
            text = row["doc"] + ("\n\n" + notes[name] if name in notes else "")
            lines.append(f"    async def {method}({params}) -> {row['returns']}:\n")
            lines.append(_docstring(text, "        "))
            lines.append("        ...\n")
    members = "".join(f"    {group}: _{group.capitalize()}\n" for group in groups)
    lines.append(FOOTER.format(groups=members, **SECTIONS))
    return "".join(lines)


