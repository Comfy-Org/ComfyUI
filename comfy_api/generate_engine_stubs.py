def read_calls(source: str) -> list[tuple[str, dict]]:
    """Read the table without importing the engine."""
    tree = ast.parse(source)
    table = next(
        node.value for node in tree.body
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "CALLS"
    )
    fields = ("kind", "target", "args", "returns")
    rows = []
    for key, value in zip(table.keys, table.values):
        if value.func.id == "_hook":
            runs_on = ast.literal_eval(value.args[1])
            row = {"kind": "MODEL", "args": "fn: Hook", "returns": "Model",
                   "doc": f"Return a copy that runs a function on {runs_on} during sampling."}
        else:
            row = {name: ast.literal_eval(arg) for name, arg in zip(fields, value.args)}
            row.setdefault("args", "")
            row.setdefault("returns", "Any")
            row["doc"] = next((ast.literal_eval(k.value) for k in value.keywords if k.arg == "doc"), "")
        rows.append((ast.literal_eval(key), row))
    return rows


def _literal_dict(source: str, name: str) -> dict:
    """A module-level ``NAME: dict = {...}`` of string literals, where values may concatenate
    string constants defined earlier in the module (``"..." + _HOOK_COMMON``)."""
    tree = ast.parse(source)
    constants = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.value, ast.Constant):
            constants[getattr(node.targets[0], "id", "")] = node.value.value

    def value(expr):
        if isinstance(expr, ast.Constant):
            return expr.value
        if isinstance(expr, ast.Name):
            return constants[expr.id]
        if isinstance(expr, ast.BinOp) and isinstance(expr.op, ast.Add):
            return value(expr.left) + value(expr.right)
        raise ValueError(f"{name}: unsupported expression {ast.dump(expr)}")

    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == name:
            return {value(k): value(v) for k, v in zip(node.value.keys, node.value.values)}
    return {}


def _docstring(text: str, indent: str) -> str:
    lines = text.strip("\n").splitlines()
    body = "\n".join((indent + line) if line.strip() else "" for line in lines)
    return f'{indent}"""{body.lstrip()}\n{indent}"""\n' if len(lines) > 1 else f'{indent}"""{text.strip()}"""\n'


def _params(row: dict) -> str:
    return ", ".join(a for a in (KIND_PARAMS.get(row.get("kind")), row["args"]) if a)


def _groups(source: str) -> dict:
    groups: dict = {}
    for name, row in read_calls(source):
        group, _, method = name.partition(".")
        groups.setdefault(group, []).append((method, row))
    return groups


WIDTH = 100


def banner(title: str, rule: str = "=") -> str:
    """A section separator in the stub: a full-width rule, the title, a rule."""
    line = "# " + rule * (WIDTH - 2)
    return f"{line}\n# {title}\n{line}"


