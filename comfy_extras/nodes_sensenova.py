class SenseNovaSamplingOptions(io.ComfyNode):
    @classmethod
    def define_schema(cls) -> io.Schema:
        return io.Schema(
            node_id="SenseNovaSamplingOptions",
            display_name="SenseNova Sampling Options",
            category="model/patch/sensenova",
            description="Set the SenseNova flow shift.",
            inputs=[
                io.Model.Input(id="model"),
                io.Float.Input(id="shift", default=3.0, step=0.01),
            ],
            outputs=[io.Model.Output()],
        )

    @classmethod
    def execute(cls, *, model, shift: float) -> io.NodeOutput:
        patched = model.clone()
        model_sampling = SenseNovaModelSampling(patched.model.model_config)
        model_sampling.set_parameters(shift=shift)
        patched.add_object_patch("model_sampling", model_sampling)
        return io.NodeOutput(patched)


class SenseNovaConditioning(io.ComfyNode):
    @classmethod
    def define_schema(cls) -> io.Schema:
        return io.Schema(
            node_id="SenseNovaConditioning",
            display_name="SenseNova Conditioning",
            category="model/sampling/sensenova",
            description=(
                "Encode reference images, image thinking, interleaved text, self-correction, or multi-turn editing with CLIP. "
                "Connect HiDream-O1 Reference Images before this node and use a standard sampler for images. "
                "Text-to-image without thinking needs only CLIP Text Encode; text-only output can use Generate Text."
            ),
            inputs=[
                io.Clip.Input("clip", optional=True),
                io.Conditioning.Input("conditioning"),
                io.Conditioning.Input("negative", optional=True),
                io.DynamicCombo.Input("task", options=[
                    io.DynamicCombo.Option("image", []),
                    io.DynamicCombo.Option("image thinking", []),
                    io.DynamicCombo.Option("interleave", [
                        io.Boolean.Input("thinking", default=True),
                        io.Latent.Input("samples", optional=True,
                            tooltip="Previous sampler output, connected when continuing after an image request."),
                    ]),
                    io.DynamicCombo.Option("self-correction", [
                        io.Latent.Input("samples", optional=True,
                            tooltip="Previous sampler output, connected when continuing after an image request."),
                    ]),
                    io.DynamicCombo.Option("multi-turn edit", [
                        io.Conditioning.Input("previous", optional=True,
                            tooltip="Previous turn conditioning, connected when continuing an editing history."),
                        io.Latent.Input("samples", optional=True,
                            tooltip="Previous sampler output, connected when continuing after an image turn."),
                    ]),
                ], tooltip="Select the task. Its prompt template and stopping behavior are set automatically."),
                io.Int.Input("max_tokens", default=1024, min=1, max=8192, advanced=True,
                    tooltip="Maximum tokens generated during this call."),
            ],
            outputs=[
                io.Conditioning.Output(display_name="conditioning"),
                io.String.Output(display_name="generated_text",
                    tooltip="Text generated by this call. Use SenseNova Interleave Decode for the complete result."),
                io.Conditioning.Output(display_name="negative",
                    tooltip="Updated negative conditioning for interleave, self-correction, and multi-turn editing. "
                            "Connect this to the next turn's negative input to continue its history."),
                io.Boolean.Output(display_name="image_requested"),
            ],
        )

    @classmethod
    def execute(cls, *, conditioning, task: io.DynamicCombo.Type, max_tokens, clip=None, negative=None) -> io.NodeOutput:
        name = task["task"]
        if name not in ("image", "image thinking", "interleave", "self-correction", "multi-turn edit"):
            raise ValueError(f"Unknown SenseNova task: {name}")
        if not conditioning or conditioning[0][1].get("sensenova_interleave_finished"):
            return io.NodeOutput(conditioning, "", negative or [], False, ui=ui.PreviewText(""))
        if clip is None:
            raise ValueError("Connect CLIP to SenseNova Conditioning.")
        if name == "image":
            return io.NodeOutput(encode_conditioning(clip, conditioning), "", encode_conditioning(clip, negative or [], image_only=True), True)
        if name == "multi-turn edit":
            return cls._execute_multi_turn_edit(
                clip=clip,
                positive=conditioning,
                negative=negative,
                previous=task.get("previous"),
                samples=task.get("samples"),
            )
        mode = "interleave" if name == "interleave" else "image"
        thinking = name == "image thinking" or (name == "interleave" and task["thinking"])
        positive = prepare_generation_conditioning(clip, conditioning, mode, thinking)
        if name == "image thinking":
            return cls._execute_image(clip=clip, conditioning=positive, max_tokens=max_tokens, negative=negative)
        negative = prepare_generation_conditioning(clip, negative or [], mode, False)
        return cls._execute_interleave(
            clip=clip, positive=positive, negative=negative,
            samples=task.get("samples"), max_text_tokens=max_tokens,
        )

    @classmethod
    def _execute_multi_turn_edit(
        cls,
        *,
        clip,
        positive,
        negative,
        previous,
        samples,
    ) -> io.NodeOutput:
        positive = _multi_turn_entries(positive, "positive")
        negative = _multi_turn_entries(negative, "negative") if negative else []
        sampled_image = None
        if previous is None:
            if samples is not None:
                raise ValueError("Connect previous conditioning together with samples when continuing an edit.")
        else:
            previous = _multi_turn_entries(previous, "previous")
            latent_samples = samples.get("samples") if isinstance(samples, dict) else None
            if latent_samples is None:
                raise ValueError("SenseNova multi-turn edit requires samples from the preceding KSampler.")
            image_tokens, image = prepare_interleave_image(latent_samples)
            sampled_image = image_tokens, image.clamp(0.0, 1.0)

        updated_positive = _encode_multi_turn_entries(clip, positive, previous, sampled_image, image_only=False)
        updated_negative = _encode_multi_turn_entries(clip, negative, None, sampled_image, image_only=True)
        return io.NodeOutput(updated_positive, "", updated_negative, True)

    @classmethod
    def _execute_image(cls, *, clip, conditioning, max_tokens, negative=None) -> io.NodeOutput:
        if len(conditioning) != 1:
            raise ValueError("SenseNova Conditioning requires one positive conditioning entry.")
        metadata = conditioning[0][1]
        if metadata.get("text_input_ids") is None:
            raise ValueError("SenseNova Conditioning requires SenseNova text conditioning.")
        token_ids, stop_token = generate_tokens(clip, metadata, max_tokens, THINK_END_ID)
        text = _decode_generated_text(clip, token_ids[:-1] if stop_token == THINK_END_ID else token_ids)
        input_ids = metadata["text_input_ids"]
        suffix = input_ids.new_tensor([*token_ids, *THINK_SUFFIX_IDS]).unsqueeze(0)
        updated_metadata = {
            **metadata,
            "text_input_ids": torch.cat((input_ids, suffix), dim=1),
            "sensenova_thinking_start": input_ids.shape[1],
        }
        return io.NodeOutput(
            encode_conditioning(clip, [[conditioning[0][0], updated_metadata]]), text,
            encode_conditioning(clip, negative or [], image_only=True), True, ui=ui.PreviewText(text),
        )

    @classmethod
    def _execute_interleave(
        cls,
        *,
        clip,
        positive,
        negative,
        samples,
        max_text_tokens,
    ) -> io.NodeOutput:
        if negative is None or len(positive) != 1 or len(negative) != 1:
            raise ValueError(
                "SenseNova interleave requires one positive and one negative conditioning entry."
            )
        if positive[0][1].get("sensenova_interleave_finished"):
            return io.NodeOutput(
                positive, "", negative, False, ui=ui.PreviewText("")
            )
        if clip is None:
            raise ValueError("Connect CLIP to SenseNova Conditioning.")
        positive_metadata = expand_interleave_metadata(positive[0][1], image_only=False)
        negative_metadata = expand_interleave_metadata(negative[0][1], image_only=True)
        pending_image = bool(
            positive_metadata.get("sensenova_interleave_pending_image")
        )
        if pending_image != bool(
            negative_metadata.get("sensenova_interleave_pending_image")
        ):
            raise ValueError("SenseNova interleave conditioning histories are out of sync.")
        latent_samples = samples.get("samples") if isinstance(samples, dict) else None
        if pending_image:
            if latent_samples is None:
                raise ValueError(
                    "SenseNova interleave is waiting for samples from the preceding KSampler."
                )
            image_tokens, image = prepare_interleave_image(latent_samples)
            positive_metadata = append_interleave_image(positive_metadata, image_tokens, image)
            negative_metadata = append_interleave_image(negative_metadata, image_tokens, image)
        elif latent_samples is not None:
            raise ValueError(
                "SenseNova interleave received samples before requesting an image."
            )

        token_ids, stop_token = generate_tokens(clip, positive_metadata, max_text_tokens, IMAGE_START_ID)

        image_requested = stop_token == IMAGE_START_ID
        positive_metadata = append_interleave_tokens(
            positive_metadata, token_ids, image_requested
        )
        positive_metadata["sensenova_interleave_finished"] = stop_token == IM_END_ID
        if image_requested:
            negative_ids = negative_metadata["text_input_ids"]
            image_start = [] if negative_ids.shape[1] and negative_ids[0, -1] == IMAGE_START_ID else [IMAGE_START_ID]
            negative_metadata = append_interleave_tokens(
                negative_metadata, image_start, True
            )
        history = positive_metadata["text_input_ids"][0, positive_metadata["sensenova_interleave_start"]:].tolist()
        think_start, think_end = _interleave_thinking_span(clip, history)
        stage_start = len(history) - len(token_ids)
        text = _decode_generated_text(clip, [
            token for index, token in enumerate(token_ids, start=stage_start)
            if index not in (think_start, think_end)
        ])
        updated_positive = encode_conditioning(clip, [[positive[0][0], positive_metadata]])
        updated_negative = encode_conditioning(clip, [[negative[0][0], negative_metadata]])
        return io.NodeOutput(
            updated_positive,
            text,
            updated_negative,
            image_requested,
            ui=ui.PreviewText(text),
        )


def prepare_generation_conditioning(clip, conditioning, mode, thinking):
    prepared = []
    for tensor, metadata in conditioning:
        if metadata.get("sensenova_interleave_expanded"):
            prepared.append([tensor, metadata])
            continue
        if "sensenova_prompt" not in metadata:
            raise ValueError("Use CLIP Text Encode with the SenseNova CLIP output before SenseNova Conditioning.")
        tokens = clip.tokenize(metadata["sensenova_prompt"], mode=mode, thinking=thinking)
        input_ids = torch.tensor([[int(value[0]) for value in batch] for batch in tokens["sensenova_u15"]], dtype=torch.long)
        updated = {**metadata, "text_input_ids": input_ids}
        updated.pop("sensenova_thinking_start", None)
        prepared.append([tensor, updated])
    return prepared



def _multi_turn_entries(conditioning, role):
    entries = [metadata for _, metadata in conditioning]
    if not entries or any(m.get("text_input_ids") is None for m in entries):
        raise ValueError(f"SenseNova multi-turn edit requires {role} SenseNova conditioning.")
    if len(entries) > 1 and any("clip_start_percent" not in m or "clip_end_percent" not in m for m in entries):
        raise ValueError(f"Multiple {role} SenseNova conditioning entries require CLIP schedule ranges.")
    return entries


def _encode_multi_turn_entries(clip, turns, previous, sampled_image, image_only):
    output = []
    for turn in turns:
        for history in (previous if previous is not None else (turn,)):
            start = max(history.get("clip_start_percent", 0.0), turn.get("clip_start_percent", 0.0))
            end = min(history.get("clip_end_percent", 1.0), turn.get("clip_end_percent", 1.0))
            if start >= end:
                continue
            clip_range = (start, end) if (start, end) != (0.0, 1.0) else None
            if sampled_image is None:
                meta = expand_multi_turn_metadata(turn, image_only)
                tokens = conditioning_tokens(meta)
                tokens["image_only"] = image_only
                entries = _encode_conditioning_entry(clip, meta, tokens, clip_range)
            else:
                entries = _encode_multi_turn_continuation(
                    clip, history, turn, *sampled_image, image_only=image_only, clip_range=clip_range,
                )
            if turn.get("hooks") is not None:
                for _, metadata in entries:
                    metadata["hooks"] = turn["hooks"]
            output.extend(entries)
    return output


def _multi_turn_metadata(metadata, input_ids, references, image_only):
    # Keep the current turn's sampler options. The encoder supplies fresh prefix and schedule state.
    updated = {k: v for k, v in metadata.items() if not k.startswith(("sensenova_", "prefix_"))
               and k not in ("pooled_output", "clip_start_percent", "clip_end_percent")}
    updated.update(text_input_ids=input_ids, reference_latents=references, sensenova_interleave_expanded=True,
                   sensenova_prompt="" if image_only else metadata.get("sensenova_prompt", ""))
    return updated


def expand_multi_turn_metadata(metadata, image_only):
    input_ids = metadata["text_input_ids"]
    references = metadata.get("reference_latents") or []
    if not metadata.get("sensenova_interleave_expanded"):
        input_ids, references = expand_interleave_inputs(input_ids, references, image_only, multi_turn=True)
    return _multi_turn_metadata(metadata, input_ids, references, image_only)


def _prefix_cache_key(clip, references):
    patcher = getattr(clip, "patcher", None)
    if patcher is not None:
        if clip.use_clip_schedule or patcher.forced_hooks is not None or patcher.injections:
            return None
        clip_key = (
            id(getattr(clip, "cond_stage_model", patcher.model)),
            patcher.patches_uuid,
            getattr(clip, "layer_idx", None),
        )
    else:
        clip_key = id(clip)
    return clip_key, tuple(id(ref) for ref in references)


def _encode_multi_turn_continuation(clip, prev_raw, turn_meta, image_tokens, image, *, image_only, clip_range):
    prev_meta = expand_multi_turn_metadata(prev_raw, image_only=image_only)
    prev_ids = prev_meta["text_input_ids"]
    if not prev_ids.shape[1] or prev_ids[0, -1].item() != IMAGE_START_ID:
        raise ValueError("Connect previous SenseNova conditioning that ends with an image request.")
    prev_refs = prev_meta["reference_latents"]
    encoded_count = len(prev_refs)
    if prev_raw.get("sensenova_interleave_expanded"):
        encoded_count = prev_raw.get("sensenova_reference_count", encoded_count)
        if encoded_count > len(prev_refs):
            raise ValueError("The previous SenseNova conditioning is missing encoded reference images.")
    if image_only:
        current_ids = turn_meta["text_input_ids"]
        current_refs = []
    else:
        current_meta = expand_multi_turn_metadata(turn_meta, image_only=False)
        current_ids = current_meta["text_input_ids"]
        current_refs = current_meta["reference_latents"]
    suffix_ids = multi_turn_suffix_ids(current_ids, image_tokens, image_only=image_only)
    if len(prev_refs) > encoded_count:
        # Reference nodes append to the list without changing the already encoded history.
        suffix_ids, added_refs = expand_interleave_inputs(suffix_ids, prev_refs[encoded_count:], False, multi_turn=True)
        current_refs = [*added_refs, *current_refs]
    combined_ids = torch.cat((prev_ids, suffix_ids.to(device=prev_ids.device)), dim=1)
    suffix_refs = [image, *current_refs]
    combined_refs = [*prev_refs[:encoded_count], *suffix_refs]
    out_meta = _multi_turn_metadata(turn_meta, combined_ids, combined_refs, image_only)
    tokens = conditioning_tokens(out_meta)
    tokens["image_only"] = image_only
    cache_key = _prefix_cache_key(clip, prev_refs)
    past_keys = prev_raw.get("prefix_keys")
    past_values = prev_raw.get("prefix_values")
    past_time = prev_raw.get("prefix_time")
    if (
        prev_raw.get("sensenova_interleave_expanded")
        and cache_key is not None
        and prev_raw.get("prefix_cache_key") == cache_key
        and past_keys is not None
        and past_values is not None
        and past_time is not None
        and int(past_keys[0].shape[2]) == int(prev_ids.shape[1])
    ):
        tokens["past_prefix_keys"] = past_keys
        tokens["past_prefix_values"] = past_values
        tokens["past_prefix_time"] = past_time
        tokens["suffix_input_ids"] = suffix_ids
        tokens["suffix_reference_latents"] = suffix_refs
    return _encode_conditioning_entry(clip, out_meta, tokens, clip_range)


def expand_interleave_metadata(metadata, image_only):
    expanded = dict(metadata)
    if expanded.get("sensenova_interleave_expanded"):
        return expanded

    input_ids = expanded["text_input_ids"]
    # Image prompts prefill an image request for direct KSampler use. A new
    # interleave session lets the model request it instead. Never strip a
    # model-generated request when resuming an already expanded history.
    if input_ids.shape[1] and input_ids[0, -1] == IMAGE_START_ID:
        input_ids = input_ids[:, :-1]
    input_ids, references = expand_interleave_inputs(
        input_ids, expanded.get("reference_latents"), image_only
    )
    expanded.update(
        {
            "text_input_ids": input_ids,
            "reference_latents": references,
            "sensenova_interleave_expanded": True,
            "sensenova_interleave_pending_image": False,
            "sensenova_interleave_start": input_ids.shape[1],
            "sensenova_interleave_input_images": len(references),
        }
    )
    return expanded


def append_interleave_tokens(metadata, token_ids, image_requested):
    updated = dict(metadata)
    if token_ids:
        suffix = updated["text_input_ids"].new_tensor(token_ids).unsqueeze(0)
        updated["text_input_ids"] = torch.cat(
            (updated["text_input_ids"], suffix), dim=1
        )
    updated["sensenova_interleave_pending_image"] = image_requested
    return updated


def append_interleave_image(metadata, image_tokens, image):
    if not metadata.get("sensenova_interleave_pending_image"):
        raise ValueError("SenseNova interleave received an image without an image request.")
    updated = append_interleave_tokens(metadata, image_tokens, False)
    updated["reference_latents"] = [*(metadata.get("reference_latents") or []), image]
    return updated


def conditioning_tokens(metadata):
    tokens = {key: metadata[key] for key in (
        "text_input_ids", "reference_latents", "sensenova_prompt", "sensenova_thinking_start",
        "sensenova_interleave_expanded", "sensenova_interleave_start",
    ) if key in metadata}
    return tokens


def _encode_conditioning_entry(clip, metadata, tokens, clip_range=None):
    output = []
    if clip_range is None:
        entries = clip.encode_from_tokens_scheduled(tokens)
    else:
        start, end = clip_range
        # CLIP's filter includes both endpoints. Exclude adjacent keyframes that only touch this range.
        bounds = {"start_percent": math.nextafter(start, end), "end_percent": math.nextafter(end, start)}
        entries = clip.encode_from_tokens_scheduled(tokens, add_dict=bounds)
    for tensor, encoded in entries:
        if clip_range is not None:
            encoded = encoded.copy()
            del encoded["start_percent"], encoded["end_percent"]
            encoded["clip_start_percent"] = max(start, encoded.get("clip_start_percent", start))
            encoded["clip_end_percent"] = min(end, encoded.get("clip_end_percent", end))
        merged = {**metadata, **encoded}
        if "prefix_keys" in encoded:
            merged["prefix_cache_key"] = _prefix_cache_key(clip, merged.get("reference_latents") or [])
        output.append([tensor, merged])
    return output


def encode_conditioning(clip, conditioning, image_only=False):
    output = []
    for _, metadata in conditioning:
        tokens = conditioning_tokens(metadata)
        tokens["image_only"] = image_only
        output.extend(_encode_conditioning_entry(clip, metadata, tokens))
    return output


def generate_tokens(clip, metadata, max_tokens, stop_token):
    tokens = conditioning_tokens(metadata)
    tokens["stop_token_ids"] = (stop_token,)
    token_ids = clip.generate(tokens, do_sample=False, max_length=max_tokens)
    stop = token_ids[-1] if token_ids and token_ids[-1] in (stop_token, IM_END_ID) else None
    if stop == IM_END_ID:
        token_ids.pop()
    return token_ids, stop


def _decode_generated_text(clip, token_ids):
    text_tokens = [token for token in token_ids if token != IMAGE_START_ID]
    return clip.decode(text_tokens, skip_special_tokens=True) if text_tokens else ""


def _interleave_thinking_span(clip, token_ids):
    """Only a leading think block is protocol; later think tags are answer text."""

    start = next((index for index, token in enumerate(token_ids) if token == THINK_START_ID), len(token_ids))
    if start == len(token_ids) or clip.decode(token_ids[:start], skip_special_tokens=False).strip():
        return len(token_ids), len(token_ids)
    end = next((index for index in range(start + 1, len(token_ids)) if token_ids[index] == THINK_END_ID), len(token_ids))
    return start, end


def _decode_interleave_text(clip, token_ids):
    start, end = _interleave_thinking_span(clip, token_ids)
    has_thinking = start < len(token_ids)
    thinking_ids = []
    if has_thinking:
        thinking_ids = token_ids[start + 1:end]
        token_ids = token_ids[end + 1:]

    outputs = []
    for ids, is_thinking in ((token_ids, False), (thinking_ids, True)):
        parts = []
        text_tokens = []
        for token_id in ids:
            if token_id == IMAGE_START_ID:
                parts.append(clip.decode(text_tokens, skip_special_tokens=True))
                text_tokens = []
                if not is_thinking:
                    parts.append("<image>")
            elif token_id not in (IMAGE_CONTEXT_ID, IMAGE_END_ID):
                text_tokens.append(token_id)
        parts.append(clip.decode(text_tokens, skip_special_tokens=True))
        outputs.append("\n\n".join(part.strip() for part in parts if part.strip()) if is_thinking else "".join(parts))
    return outputs[0], outputs[1]


class SenseNovaInterleaveDecode(io.ComfyNode):
    @classmethod
    def define_schema(cls) -> io.Schema:
        return io.Schema(
            node_id="SenseNovaInterleaveDecode",
            display_name="SenseNova Interleave Decode",
            category="model/sampling/sensenova",
            description=(
                "Extract generated text, images and thinking from the interleave "
                "history produced by SenseNova Conditioning, including U1.6 "
                "self-correction. With loops, use End Loop with "
                "accumulate disabled. Input reference images are excluded. "
                "Image consumers are skipped when no images were generated."
            ),
            inputs=[
                io.Clip.Input("clip"),
                io.Conditioning.Input("conditioning"),
                io.Latent.Input(
                    "samples",
                    optional=True,
                    tooltip="Last KSampler pixel latent, if the loop ended on an image request.",
                ),
            ],
            outputs=[
                io.String.Output(display_name="text"),
                io.Image.Output(display_name="images", is_output_list=True),
                io.String.Output(display_name="thinking"),
            ],
        )

    @classmethod
    def execute(
        cls,
        clip,
        conditioning,
        samples=None,
    ) -> io.NodeOutput:
        if len(conditioning) != 1 or "sensenova_interleave_start" not in conditioning[0][1]:
            raise ValueError(
                "SenseNova Interleave Decode requires interleave conditioning from SenseNova Conditioning."
            )
        metadata = conditioning[0][1]
        if metadata["sensenova_interleave_pending_image"]:
            if samples is None:
                raise ValueError(
                    "SenseNova Interleave Decode is waiting for samples from the last KSampler. "
                    "Connect its LATENT output to samples."
                )
            metadata = append_interleave_image(metadata, *prepare_interleave_image(samples["samples"]))
        token_ids = metadata["text_input_ids"][0, metadata["sensenova_interleave_start"]:].tolist()
        text, thinking = _decode_interleave_text(clip, token_ids)
        images = [
            reference.clamp(0.0, 1.0)
            for reference in metadata["reference_latents"][metadata["sensenova_interleave_input_images"]:]
        ]
        return io.NodeOutput(text, images or [ExecutionBlocker(None)], thinking)


class SenseNovaExtension(ComfyExtension):
    @override
    async def get_node_list(self) -> list[type[io.ComfyNode]]:
        return [
            SenseNovaConditioning,
            SenseNovaSamplingOptions,
            SenseNovaInterleaveDecode,
        ]


async def comfy_entrypoint() -> SenseNovaExtension:
    return SenseNovaExtension()
